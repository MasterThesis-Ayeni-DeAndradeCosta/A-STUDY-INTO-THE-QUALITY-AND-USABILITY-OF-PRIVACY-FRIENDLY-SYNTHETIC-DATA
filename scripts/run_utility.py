import pandas as pd
from modelOperations.ml_data_preprocessing import prepare_original_data, prepare_synthetic_data
from modelOperations.model_training import train_models

def run_utility(cleaned_data, test_set, target_column, enable_synthetic, config, synthetic_datasets=None, anonymous_data=None, hybrid_data=None, logger=None):
    """
    Handles dataset preparation and model training.
    """

    print("Preparing datasets for machine learning...")
    if logger:
        logger.info("[UTILITY] Preparing datasets for machine learning...")

    # Extract X (features) and y (target) from the training set
    X_train_original = cleaned_data.drop(columns=[target_column])
    y_train_original = cleaned_data[target_column]

    # Extract X_test and y_test from the test set
    X_test_original = test_set.drop(columns=[target_column])
    y_test_original = test_set[target_column]

    print(f"Original Data - Training Size: {len(X_train_original)}, Testing Size: {len(X_test_original)}")
    if logger:
        logger.info(f"[UTILITY] Original Data - Training Size: {len(X_train_original)}, Testing Size: {len(X_test_original)}")
        logger.info(f"[UTILITY] Target class distribution (Original): {y_train_original.value_counts().to_dict()}") 

    # Dictionary to store all datasets
    datasets = {"Original": (X_train_original, y_train_original)}

    # Handle synthetic datasets if provided
    if synthetic_datasets:
        for synth_name, synthetic_data in synthetic_datasets.items():
            y_synth = synthetic_data[target_column]
            if y_synth.nunique() < 2:
                msg = f" Skipping synthetic dataset '{synth_name}' - only one class in target."
                print(msg)
                if logger:
                    logger.warning(msg)
                continue
            print(f"\nProcessing synthetic dataset generated by {synth_name}...")
            if logger:
                logger.info(f"[UTILITY] Processing synthetic dataset generated by {synth_name}...")
            X_synth = synthetic_data.drop(columns=[target_column])
            y_synth = synthetic_data[target_column]
            datasets[synth_name] = (X_synth, y_synth)
            print(f"Synthetic Data ({synth_name}) - Training Size: {len(X_synth)}")
            if logger:
                logger.info(f"[UTILITY] Synthetic Data ({synth_name}) - Training Size: {len(X_synth)}")
                logger.info(f"[UTILITY] Target class distribution ({synth_name}): {y_synth.value_counts().to_dict()}")

    # Handle anonymized dataset if provided
    # Anonymized dataset
    if anonymous_data is not None:
        y_anon = anonymous_data[target_column]
        if y_anon.nunique() >= 2:
            print("\nProcessing anonymized dataset...")
            if logger:
                logger.info("[UTILITY] Processing anonymized dataset...")
            X_anon = anonymous_data.drop(columns=[target_column])
            datasets["Anonymous"] = (X_anon, y_anon)
            print(f"Anonymized Data - Training Size: {len(X_anon)}")
            if logger:
                logger.info(f"[UTILITY] Anonymized Data - Training Size: {len(X_anon)}")
                logger.info(f"[UTILITY] Target class distribution (Anonymous): {y_anon.value_counts().to_dict()}")
        else:
            msg = " Skipping Anonymous dataset - only one class in target."
            print(msg)
            if logger:
                logger.warning(msg)
    
    
    if hybrid_data:
        for synth_name, hybrid_df in hybrid_data.items():
            y_hybrid = hybrid_df[target_column]
            hybrid_key = f"{synth_name}_HYBRID"
            if y_hybrid.nunique() < 2:
                msg = f" Skipping hybrid dataset '{hybrid_key}' - only one class in target."
                print(msg)
                if logger:
                    logger.warning(msg)
                continue
            print(f"\nProcessing hybrid dataset generated by {synth_name}...")
            if logger:
                logger.info(f"[UTILITY] Processing hybrid dataset generated by {synth_name}...")
            X_hybrid = hybrid_df.drop(columns=[target_column])
            datasets[hybrid_key] = (X_hybrid, y_hybrid)
            print(f"Hybrid Data ({hybrid_key}) - Training Size: {len(X_hybrid)}")
            if logger:
                logger.info(f"[UTILITY] Hybrid Data ({hybrid_key}) - Training Size: {len(X_hybrid)}")
                logger.info(f"[UTILITY] Target class distribution ({hybrid_key}): {y_hybrid.value_counts().to_dict()}")  # NEW

    # Train models on all available datasets
    print("\nTraining models on all datasets...")
    if logger:
        logger.info("[UTILITY] Training models on all datasets...")
        logger.info(f"[UTILITY] Total datasets used for training: {len(datasets)}")


    #trained_models = train_models(datasets, config)
    #safe version:
    try:
        trained_models = train_models(datasets, config, logger=logger)
    except Exception as e:
        print(f"❌ Model training failed: {e}")
        if logger:
            logger.exception("[UTILITY] ERROR Model training failed due to an error.")
        raise


    print("\nModel Training Completed.")
    if logger:
        logger.info(f"[UTILITY] Trained model names: {list(trained_models.keys())}") 
        logger.info("[UTILITY] Model Training Completed.")
    return trained_models, X_test_original, y_test_original, datasets

